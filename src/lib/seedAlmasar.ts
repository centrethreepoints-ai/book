export interface SeedLesson {
  title: string;
  pageStart: number;
  pageEnd: number;
  /** إن كان عنصره تدريبياً (أنشطة/ملف/تمارين) وليس درساً كاملاً */
  activityLike?: boolean;
}

export interface SeedAxis {
  title: string;
  pageStart: number;
  pageEnd: number;
  lessons: SeedLesson[];
}

export interface SeedUnit {
  title: string;
  pageStart: number;
  pageEnd: number;
  subject: string;
  kind?: 'unit' | 'domain';
  axes: SeedAxis[];
}

export interface BookSeed {
  level: string;
  units: SeedUnit[];
}

const L = (title: string, pageStart: number, pageEnd: number, activityLike = false): SeedLesson => ({
  title,
  pageStart,
  pageEnd,
  activityLike,
});

